// Preserve runtime JSON imports while bounding the checker's literal type graph.
// Every source byte and structural field is checked; no global JSON/any override.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { format } from 'prettier';

export const catalogJsonSources = ['data/art.json', 'data/editorial/reviews.json'];
const sha = (bytes) => createHash('sha256').update(bytes).digest('hex');
const node = () => ({ kinds: new Set(), objects: 0, fields: new Map(), item: null });
function observe(shape, value, depth = 0) {
  if (depth > 64) throw Error('Catalog JSON exceeds the supported structural depth');
  if (value === null) return void shape.kinds.add('null');
  const kind = Array.isArray(value) ? 'array' : typeof value;
  if (!['array', 'object', 'boolean', 'number', 'string'].includes(kind))
    throw Error('Unsupported catalog JSON value');
  if (kind === 'number' && !Number.isFinite(value)) throw Error('Non-finite catalog JSON number');
  shape.kinds.add(kind);
  if (kind === 'array') {
    shape.item ??= node();
    for (const item of value) observe(shape.item, item, depth + 1);
  } else if (kind === 'object') {
    shape.objects++;
    for (const [key, child] of Object.entries(value)) {
      let field = shape.fields.get(key);
      if (!field) {
        field = { present: 0, shape: node() };
        shape.fields.set(key, field);
      }
      field.present++;
      observe(field.shape, child, depth + 1);
    }
  }
}
function typeOf(shape, depth = 0) {
  const indent = '  '.repeat(depth),
    parts = [];
  for (const kind of [...shape.kinds].sort()) {
    if (kind === 'array') parts.push('Array<' + typeOf(shape.item, depth) + '>');
    else if (kind === 'object') {
      const fields = [...shape.fields].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
      parts.push(
        fields.length
          ? '{\n' +
              fields
                .map(
                  ([key, field]) =>
                    indent +
                    '  ' +
                    JSON.stringify(key) +
                    (field.present < shape.objects ? '?' : '') +
                    ': ' +
                    typeOf(field.shape, depth + 1) +
                    ';',
                )
                .join('\n') +
              '\n' +
              indent +
              '}'
          : 'Record<string, never>',
      );
    } else parts.push(kind);
  }
  return parts.join(' | ') || 'never';
}
export async function catalogJsonDeclaration(bytes, sourcePath) {
  if (!catalogJsonSources.includes(sourcePath)) throw Error('Explicit catalog source required');
  const shape = node();
  observe(shape, JSON.parse(bytes));
  return format(
    '// Generated by scripts/jotclipart/catalog-json-types.mjs. Do not edit.\n' +
      '// Runtime imports still read the original JSON; the CI gate verifies every source byte.\n' +
      '// Source: ' +
      sourcePath +
      '\n// Source SHA-256: ' +
      sha(bytes) +
      '\n// Source bytes: ' +
      bytes.length +
      '\n' +
      'declare const source: ' +
      typeOf(shape) +
      ';\nexport default source;\n',
    { parser: 'typescript', singleQuote: true, printWidth: 100 },
  );
}
export async function checkCatalogJsonTypes({ root = process.cwd(), write = false } = {}) {
  const evidence = [];
  for (const file of catalogJsonSources) {
    const bytes = readFileSync(resolve(root, file)),
      declaration = file.replace(/\.json$/, '.d.json.ts'),
      expected = await catalogJsonDeclaration(bytes, file);
    if (write) writeFileSync(resolve(root, declaration), expected);
    else if (readFileSync(resolve(root, declaration), 'utf8') !== expected)
      throw Error('Catalog JSON declaration is stale or changed: ' + declaration);
    evidence.push({
      source: file,
      bytes: bytes.length,
      sourceSHA256: sha(bytes),
      declaration,
      declarationSHA256: sha(expected),
    });
  }
  return { status: 'EXACT_CATALOG_JSON_BYTES_AND_STRUCTURAL_TYPES_VERIFIED', sources: evidence };
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  if (![undefined, '--check', '--write'].includes(process.argv[2]))
    throw Error('Use --check or --write');
  console.log(
    JSON.stringify(await checkCatalogJsonTypes({ write: process.argv[2] === '--write' })),
  );
}
